const { selectedLang } = useCvLang()

export const i18n = createI18n({
    legacy: false,
    locale: selectedLang.value,
    fallbackLocale: 'vi',
    messages: { vi, en },
})

// works outside components (lib/services) and in specs that mount without the i18n plugin
export const t = i18n.global.t

/** Translates `s` when it is a message key, else returns it as-is — lets field configs mix keys and literal text. */
export const tr = (s?: string) => (s && i18n.global.te(s) ? t(s) : s)

watch(
    selectedLang,
    lang => {
        i18n.global.locale.value = lang
        document.documentElement.lang = lang
    },
    { immediate: true },
)
