const { selectedLang } = useCvLang()

export const i18n = createI18n({
    legacy: false,
    locale: selectedLang.value,
    fallbackLocale: 'vi',
    messages: { vi, en },
})

// works outside components (lib/services) and in specs that mount without the i18n plugin
export const t = i18n.global.t

const PARAMS_SEP = '::'

/** Packs a message key and its params into one string, for places that only take a string (yup messages, field labels). `tr` unpacks it. */
export const withParams = (key: string, params: Record<string, string | number>) => `${key}${PARAMS_SEP}${JSON.stringify(params)}`

/** Translates `s` when it is a message key (optionally packed by `withParams`, string params translated too), else returns it as-is — lets field configs mix keys and literal text. */
export const tr = (s?: string): string | undefined => {
    if (!s) return s
    const sep = s.indexOf(PARAMS_SEP)
    const key = sep === -1 ? s : s.slice(0, sep)
    if (!i18n.global.te(key)) return s
    if (sep === -1) return t(key)
    const params: Record<string, string | number> = JSON.parse(s.slice(sep + PARAMS_SEP.length))
    return t(key, Object.fromEntries(Object.entries(params).map(([k, v]) => [k, typeof v === 'string' ? (tr(v) as string) : v])))
}

watch(
    selectedLang,
    lang => {
        i18n.global.locale.value = lang
        document.documentElement.lang = lang
    },
    { immediate: true },
)
